// i18n.go — минимальная локализация консоли лаунчера. Если основной язык
// системы русский — выводим текст на русском, иначе на английском. Никаких
// файлов ресурсов/каталогов сообщений — на таком объёме текста хватает пары
// строк RU/EN прямо по месту вызова. Само определение языка платформенное,
// см. i18n_windows.go и i18n_linux.go.
package main

var isRussian = detectRussian()

// t возвращает ru, если система на русском, иначе en. Обёртка нужна только
// ради читаемости на месте вызова (t("...", "...") короче, чем if/else).
func t(ru, en string) string {
	if isRussian {
		return ru
	}
	return en
}
